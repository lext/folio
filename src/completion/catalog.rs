/// Body inserted between `\begin{name}` and `\end{name}`. `¦` marks the caret.
pub fn environment_body(name: &str) -> &'static str {
    match name {
        "itemize" | "enumerate" => "\\item ¦",
        "description" => "\\item[¦] ",
        "figure" | "figure*" => {
            "\\centering\n\\includegraphics[width=\\linewidth]{¦}\n\\caption{}\n\\label{fig:}"
        }
        "table" | "table*" => {
            "\\centering\n\\caption{¦}\n\\label{tab:}\n\\begin{tabular}{}\n\\end{tabular}"
        }
        "frame" => "¦",
        "thebibliography" => "\\bibitem{¦}",
        _ => "¦",
    }
}
